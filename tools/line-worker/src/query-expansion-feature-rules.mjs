// 商品名は売り手の言葉で書かれている（そこまで洗える／汁漏れしない／すべらない）。
// この2つの言葉が違うと、モールの AND 検索は 0 件か、無関係な一般商品だけになる。
//
// ここでは「利用者の機能語 × カテゴリ語」→「売り手の語 ＋ カテゴリ語」の対応を規則として
// 持つ。各規則は
//   match:               利用者の言い方（正規表現。特徴語とカテゴリ語の両方を要求する）
//   primary:             正式名詞（検索本文へ合流）
//   marketplaceKeywords: モール検索の第1候補にそのまま渡す語（index.mjs）
//   synonyms/related:    順位付け（knowledge-search.mjs expansionMatchScore）と AI 用の手掛かり
//   broad:               最後の受け皿（カテゴリ語）
//   sample:              テスト用の代表クエリ
//   teacher:             教師データ（evaluation/teacher-dataset）へ書き出す元情報
// を持つ。scripts/build-feature-teacher-batch.mjs が teacher からバッチ JSON を生成する。
//
// 追加時の注意: match は必ずカテゴリ語を要求する（「滑らない」だけで靴下・まな板・ハンガーを
// 全部引かない）。既存の EXPANSION_RULES と重複マッチしないこと（query-expansion.test.mjs が
// 各規則の sample で rule_id を検証する）。

