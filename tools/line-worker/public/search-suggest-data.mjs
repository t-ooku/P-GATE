const normalize = (value) => String(value || '').normalize('NFKC').trim();

// 入力文からジャンルを特定して、そのジャンルのブランド・絞り込み語を返す。
export function detectSuggestionCategory(query) {
  const text = normalize(query);
  if (!text) return null;
  return CATEGORY_SUGGESTIONS.find((entry) => entry.match.test(text)) || null;
}

// 入力中の候補（Amazon風）: 「入力文 + ブランド」「入力文 + 絞り込み語」を、既に含む語は除いて返す。
export function suggestQueries(query, { limit = 10, extra = [] } = {}) {
  const text = normalize(query);
  if (text.length < 1) return [];
  const category = detectSuggestionCategory(text);
  const lower = text.toLowerCase();
  const out = [];
  const seen = new Set([lower]);
  const push = (candidate, kind) => {
    const value = normalize(candidate);
    if (!value || seen.has(value.toLowerCase())) return;
    seen.add(value.toLowerCase());
    out.push({ query: value, kind });
  };
  for (const item of extra) push(item.query || item, item.kind || 'history');
  if (category) {
    // 関連ワードとメーカーを交互に並べ、上位数件にどちらも入るようにする（Amazonの並びに近づける）。
    const modifiers = category.modifiers.filter((modifier) => !lower.includes(modifier.toLowerCase()));
    const brands = category.brands.filter((brand) => !lower.includes(brand.toLowerCase()));
    const length = Math.max(modifiers.length, brands.length);
    for (let index = 0; index < length; index += 1) {
      if (modifiers[index]) push(`${text} ${modifiers[index]}`, 'related');
      if (brands[index]) push(`${text} ${brands[index]}`, 'brand');
    }
  } else {
    for (const modifier of GENERIC_MODIFIERS) {
      if (!lower.includes(modifier.toLowerCase())) push(`${text} ${modifier}`, 'related');
    }
  }
  return out.slice(0, limit);
}
